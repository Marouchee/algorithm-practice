"""백준 1463 1로 만들기 (DP)
https://www.acmicpc.net/problem/1463

접근: dp[i] = i를 1로 만드는 최소 연산 횟수. dp[1] = 0에서 시작해 i를 2부터 올려 가며
      dp[i-1] + 1, (2로 나누어떨어지면) dp[i//2] + 1, (3으로 나누어떨어지면) dp[i//3] + 1 중 최솟값을 넣는다.
      작은 칸이 항상 먼저 채워지므로 반복문으로 계산한다 (재귀는 1을 빼는 경로에서 최대 100만 겹이라 위험).
      "3 → 2 → 1 빼기" 순서의 그리디는 10에서 4번(10 5 4 2 1)이 나와 최솟값 3번(10 9 3 1)을 놓친다.
시간 복잡도: O(N). 칸마다 최대 3번 비교 (N = 1,000,000이면 약 300만 번)
테스트: python3 baekjoon/test_1463_1로_만들기.py
"""
n = int(input())
dp = [1000000 for _ in range(n+1)]
dp[1] = 0

for i in range(2,n+1):
    if i % 2 == 0:
        if dp[i] > dp[i//2] + 1:
            dp[i] = dp[i//2] + 1
    if i % 3 == 0:
        if dp[i] > dp[i//3] + 1:
            dp[i] = dp[i//3] + 1
    if dp[i] > dp[i-1] + 1:
        dp[i] = dp[i-1] + 1

print(dp[n])
